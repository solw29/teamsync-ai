import React from 'react';
import {afterEach,expect,it,vi} from 'vitest';
import {act,cleanup,render} from '@testing-library/react';
import {z} from 'zod';
import {ApiClient,ApiError} from './client';
import {useVisiblePoll} from './ApiWorkspace';
afterEach(()=>{cleanup();vi.restoreAllMocks();vi.unstubAllGlobals();vi.useRealTimers()});
it('sends session credentials and CSRF while validating the server contract',async()=>{
 const fetcher=vi.fn().mockResolvedValue(new Response(JSON.stringify({id:'result'})));
 vi.stubGlobal('fetch',fetcher);
 const client=new ApiClient('/api','csrf-fixture');
 expect(await client.request('/resource',z.object({id:z.string()}),{method:'POST'})).toEqual({id:'result'});
 expect(fetcher).toHaveBeenCalledWith('/api/resource',expect.objectContaining({credentials:'include',headers:expect.objectContaining({'X-CSRF-Token':'csrf-fixture'})}));
 fetcher.mockResolvedValueOnce(new Response(JSON.stringify({id:42})));
 await expect(client.request('/resource',z.object({id:z.string()}))).rejects.toThrow();
});
it('expires authentication on 401 and never substitutes a demo response',async()=>{
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue(new Response(JSON.stringify({error:{code:'authentication_required'}}),{status:401})));
 const expired=vi.fn();const client=new ApiClient('/api','',expired);
 await expect(client.request('/runs',z.object({items:z.array(z.string())}))).rejects.toEqual(new ApiError('authentication_required',401));
 expect(expired).toHaveBeenCalledOnce();
});
it('polls only active visible work and cancels in-flight work when hidden/unmounted',()=>{
 vi.useFakeTimers();let visibility='visible';vi.spyOn(document,'visibilityState','get').mockImplementation(()=>visibility as DocumentVisibilityState);
 const cancel=vi.fn(),request=vi.fn(()=>cancel);
 function Probe({active}:{active:boolean}){useVisiblePoll(request,active);return <span/>}
 const view=render(<Probe active={true}/>);
 act(()=>vi.advanceTimersByTime(10000));expect(request).toHaveBeenCalledTimes(1);
 visibility='hidden';act(()=>document.dispatchEvent(new Event('visibilitychange')));expect(cancel).toHaveBeenCalledOnce();
 act(()=>vi.advanceTimersByTime(30000));expect(request).toHaveBeenCalledTimes(1);
 visibility='visible';act(()=>document.dispatchEvent(new Event('visibilitychange')));expect(request).toHaveBeenCalledTimes(2);
 view.rerender(<Probe active={false}/>);expect(cancel).toHaveBeenCalledTimes(2);
 act(()=>vi.advanceTimersByTime(20000));expect(request).toHaveBeenCalledTimes(2);
});

it('accepts fixtures generated by FastAPI response models',async()=>{
 const {listSchema,detailSchema,statsSchema}=await import('./client');
 const runs=await import('../../../docs/backend/contract/runs.json');
 const detail=await import('../../../docs/backend/contract/detail.json');
 const stats=await import('../../../docs/backend/contract/stats.json');
 expect(listSchema.parse(runs.default).items).toHaveLength(1);
 expect(detailSchema.parse(detail.default).runAttempt).toBe(1);
 expect(statsSchema.parse(stats.default).total).toBe(1);
});

it.each([403,500])('preserves a %i server failure without returning demo rows',async(status)=>{
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue(new Response(JSON.stringify({error:{code:'server_failure'}}),{status})));
 const expired=vi.fn();const client=new ApiClient('/api','',expired);
 await expect(client.request('/runs',z.object({items:z.array(z.string())}))).rejects.toEqual(new ApiError('server_failure',status));
 expect(expired).not.toHaveBeenCalled();
});
